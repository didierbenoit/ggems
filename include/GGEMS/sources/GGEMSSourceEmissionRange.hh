#pragma once

#include <cstdint>

namespace ggems::core::sources {

/*! \brief Locates one emission group within a source-local primary range. */
struct GGEMSSourceEmissionRange {
  /*! \brief Inclusive first primary index within the owning source slot. */
  std::uint64_t source_local_primary_begin{0ULL};

  /*! \brief Number of primaries in this emission group, possibly zero. */
  std::uint64_t primary_count{0ULL};
};

} // namespace ggems::core::sources
