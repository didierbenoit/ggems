TEST(GGEMSSr82Test, PreservesIdentityAndOrderedMarginalYields) {
  auto const definition = BuildSr82Radionuclide();
  EXPECT_EQ(definition.GetCanonicalName(), "Sr-82");
  // LNHB evaluated 25.347 d, converted exactly to seconds.
  EXPECT_EQ(definition.GetHalfLifeSeconds(), 2189980.800L);
  auto const emissions = definition.GetEmissions();
  ASSERT_EQ(emissions.size(), 1U);
  // Independent selected LNHB values; see data/Sr-82/reference/README.md.
  // Physical yields are not a categorical probability distribution.
  // atomic_xray
  EXPECT_EQ(emissions[0U].GetParticleType(), GGEMSParticleType::Gamma);
  GGEMS_EXPECT_NEAR_LD(emissions[0U].GetYieldPerDecay(), 0.6041L, 1.0e-16L);
  EXPECT_EQ(emissions[0U].GetEnergyDistribution().GetType(),
            GGEMSEnergyDistributionType::DiscreteLines);
  GGEMS_EXPECT_NEAR_LD(definition.GetTotalYieldPerDecay(), 0.6041L, 1.0e-14L);
}

