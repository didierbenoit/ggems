[[nodiscard]] auto BuildSr89Radionuclide() -> GGEMSRadionuclideDefinition {
  std::vector<GGEMSRadionuclideEmission> emissions;
  emissions.reserve(3U);

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_beta_minus_586_1_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_minus_586_1_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_minus_586_1_keV_bin_width_micro_eV,
      },
      k_beta_minus_586_1_keV_weights));

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_beta_minus_1495_1_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_minus_1495_1_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_minus_1495_1_keV_bin_width_micro_eV,
      },
      k_beta_minus_1495_1_keV_weights));

  emissions.emplace_back(
    particles::GGEMSParticleType::Gamma, k_atomic_xray_yield,
    sources::GGEMSEnergyDistribution::BuildMono(k_atomic_xray_energy_micro_eV));

  return {"Sr-89", k_half_life_seconds, std::move(emissions)};
}

