[[nodiscard]] auto BuildCs137Radionuclide() -> GGEMSRadionuclideDefinition {
  std::vector<GGEMSRadionuclideEmission> emissions;
  emissions.reserve(3U);

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_beta_minus_513_97_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_minus_513_97_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_minus_513_97_keV_bin_width_micro_eV,
      },
      k_beta_minus_513_97_keV_weights));

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_beta_minus_892_17_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_minus_892_17_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_minus_892_17_keV_bin_width_micro_eV,
      },
      k_beta_minus_892_17_keV_weights));

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_beta_minus_1175_63_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_minus_1175_63_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_minus_1175_63_keV_bin_width_micro_eV,
      },
      k_beta_minus_1175_63_keV_weights));

  return {"Cs-137", k_half_life_seconds, std::move(emissions)};
}

