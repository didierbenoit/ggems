[[nodiscard]] auto BuildNa22Radionuclide() -> GGEMSRadionuclideDefinition {
  std::vector<GGEMSRadionuclideEmission> emissions;
  emissions.reserve(5U);

  emissions.emplace_back(
    particles::GGEMSParticleType::Positron, k_beta_plus_546_45_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_plus_546_45_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_plus_546_45_keV_bin_width_micro_eV,
      },
      k_beta_plus_546_45_keV_weights));

  emissions.emplace_back(
    particles::GGEMSParticleType::Positron, k_beta_plus_1821_02_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_plus_1821_02_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_plus_1821_02_keV_bin_width_micro_eV,
      },
      k_beta_plus_1821_02_keV_weights));

  emissions.emplace_back(particles::GGEMSParticleType::Gamma,
                         k_nuclear_gamma_yield,
                         sources::GGEMSEnergyDistribution::BuildMono(
                           k_nuclear_gamma_energy_micro_eV));

  emissions.emplace_back(
    particles::GGEMSParticleType::Gamma, k_atomic_xray_yield,
    sources::GGEMSEnergyDistribution::BuildMono(k_atomic_xray_energy_micro_eV));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_conversion_1274_537_keV_yield,
                         sources::GGEMSEnergyDistribution::BuildMono(
                           k_conversion_1274_537_keV_energy_micro_eV));

  return {"Na-22", k_half_life_seconds, std::move(emissions)};
}

