[[nodiscard]] auto BuildY90Radionuclide() -> GGEMSRadionuclideDefinition {
  std::vector<GGEMSRadionuclideEmission> emissions;
  emissions.reserve(4U);

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_beta_minus_92_4_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_minus_92_4_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_minus_92_4_keV_bin_width_micro_eV,
      },
      k_beta_minus_92_4_keV_weights));

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_beta_minus_518_0_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_minus_518_0_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_minus_518_0_keV_bin_width_micro_eV,
      },
      k_beta_minus_518_0_keV_weights));

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_beta_minus_2278_7_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_minus_2278_7_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_minus_2278_7_keV_bin_width_micro_eV,
      },
      k_beta_minus_2278_7_keV_weights));

  emissions.emplace_back(particles::GGEMSParticleType::Gamma,
                         k_nuclear_gamma_yield,
                         sources::GGEMSEnergyDistribution::BuildMono(
                           k_nuclear_gamma_energy_micro_eV));

  return {"Y-90", k_half_life_seconds, std::move(emissions)};
}

