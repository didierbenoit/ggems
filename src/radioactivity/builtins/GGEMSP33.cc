/*!
 * \file
 * \brief Defines the compiled P-33 marginal source-emission spectrum.
 *
 * CEA/LNE-LNHB, M.-C. Lepy, March 2026: 100% allowed beta-minus decay
 * to stable S-33 ground state, with Q and endpoint
 * 248.5(11) keV. The evaluated 25.38(5) d half-life is converted
 * with exact 86400 s/d; rounded LARA seconds are not substituted.
 *
 * BetaShape 2.4 (06/2024), beta-_P33_trans0.bs: selected dN/dE calc.
 * No tabulated experimental shape factor is available. The reported
 * calculated mean is 75.91 keV, also adopted by the LNHB evaluation.
 *
 * The retained piecewise-linear density is integrated offline into regular
 * bins and normalized conditionally; the physical yield is one electron per
 * parent decay. The historical even-integer-meV grid is scaled exactly by
 * 1000 to canonical micro-eV, with width at most 0.5 keV and exact upper
 * endpoint. Its positive lower edge excludes a reference probability of
 * 9.55783724989e-06; the independent reference retains that lower tail.
 * The continuous law and finite grid are distinct representations.
 *
 * Raw evidence and the full selected spectrum are retained under
 * validation/radioactivity/data/P-33/. ENSDF and MIRD are independent
 * cross-checks only. No separate photon, atomic, recoil or antineutrino
 * source group is selected.
 *
 * \author Julien BERT <julien.bert@univ-brest.fr>
 * \author Didier BENOIT <didier.benoit@inserm.fr>
 */

