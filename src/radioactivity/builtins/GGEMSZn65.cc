[[nodiscard]] auto BuildZn65Radionuclide() -> GGEMSRadionuclideDefinition {
  std::vector<GGEMSRadionuclideEmission> emissions;
  emissions.reserve(6U);

  emissions.emplace_back(
    particles::GGEMSParticleType::Positron, k_beta_plus_330_1_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_plus_330_1_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_plus_330_1_keV_bin_width_micro_eV,
      },
      k_beta_plus_330_1_keV_weights));

  emissions.emplace_back(
    particles::GGEMSParticleType::Gamma, k_nuclear_gamma_yield,
    sources::GGEMSEnergyDistribution::BuildDiscreteLines(
      k_nuclear_gamma_energies_micro_eV, k_nuclear_gamma_line_yields));

  emissions.emplace_back(
    particles::GGEMSParticleType::Gamma, k_atomic_xray_yield,
    sources::GGEMSEnergyDistribution::BuildDiscreteLines(
      k_atomic_xray_energies_micro_eV, k_atomic_xray_line_yields));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_conversion_344_95_keV_yield,
                         sources::GGEMSEnergyDistribution::BuildDiscreteLines(
                           k_conversion_344_95_keV_energies_micro_eV,
                           k_conversion_344_95_keV_line_yields));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_conversion_770_64_keV_yield,
                         sources::GGEMSEnergyDistribution::BuildDiscreteLines(
                           k_conversion_770_64_keV_energies_micro_eV,
                           k_conversion_770_64_keV_line_yields));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_conversion_1115_539_keV_yield,
                         sources::GGEMSEnergyDistribution::BuildDiscreteLines(
                           k_conversion_1115_539_keV_energies_micro_eV,
                           k_conversion_1115_539_keV_line_yields));

  return {"Zn-65", k_half_life_seconds, std::move(emissions)};
}

