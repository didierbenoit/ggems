[[nodiscard]] auto BuildTb161Radionuclide() -> GGEMSRadionuclideDefinition {
  std::vector<GGEMSRadionuclideEmission> emissions;
  emissions.reserve(6U);

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_beta_minus_aggregate_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_minus_aggregate_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_minus_aggregate_bin_width_micro_eV,
      },
      k_beta_minus_aggregate_weights));

  emissions.emplace_back(
    particles::GGEMSParticleType::Gamma, k_nuclear_gamma_yield,
    sources::GGEMSEnergyDistribution::BuildDiscreteLines(
      k_nuclear_gamma_energies_micro_eV, k_nuclear_gamma_line_yields));

  emissions.emplace_back(
    particles::GGEMSParticleType::Gamma, k_atomic_xray_yield,
    sources::GGEMSEnergyDistribution::BuildDiscreteLines(
      k_atomic_xray_energies_micro_eV, k_atomic_xray_line_yields));

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_auger_electron_yield,
    sources::GGEMSEnergyDistribution::BuildDiscreteLines(
      k_auger_electron_energies_micro_eV, k_auger_electron_line_yields));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_conversion_electron_yield,
                         sources::GGEMSEnergyDistribution::BuildDiscreteLines(
                           k_conversion_electron_energies_micro_eV,
                           k_conversion_electron_line_yields));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_conversion_electron_weak_1_yield,
                         sources::GGEMSEnergyDistribution::BuildMono(
                           k_conversion_electron_weak_1_energy_micro_eV));

  return {"Tb-161", k_half_life_seconds, std::move(emissions)};
}

