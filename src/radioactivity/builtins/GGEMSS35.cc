[[nodiscard]] auto BuildS35Radionuclide() -> GGEMSRadionuclideDefinition {
  std::vector<GGEMSRadionuclideEmission> emissions;
  emissions.reserve(1U);

  emissions.emplace_back(
    particles::GGEMSParticleType::Electron, k_beta_minus_167_33_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_minus_167_33_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_minus_167_33_keV_bin_width_micro_eV,
      },
      k_beta_minus_167_33_keV_weights));

  return {"S-35", k_half_life_seconds, std::move(emissions)};
}

