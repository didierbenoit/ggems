[[nodiscard]] auto BuildMn54Radionuclide() -> GGEMSRadionuclideDefinition {
  std::vector<GGEMSRadionuclideEmission> emissions;
  emissions.reserve(4U);

  emissions.emplace_back(
    particles::GGEMSParticleType::Positron, k_beta_plus_355_2_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_plus_355_2_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_plus_355_2_keV_bin_width_micro_eV,
      },
      k_beta_plus_355_2_keV_weights));

  emissions.emplace_back(particles::GGEMSParticleType::Gamma,
                         k_nuclear_gamma_yield,
                         sources::GGEMSEnergyDistribution::BuildMono(
                           k_nuclear_gamma_energy_micro_eV));

  emissions.emplace_back(
    particles::GGEMSParticleType::Gamma, k_atomic_xray_yield,
    sources::GGEMSEnergyDistribution::BuildDiscreteLines(
      k_atomic_xray_energies_micro_eV, k_atomic_xray_line_yields));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_conversion_834_848_keV_yield,
                         sources::GGEMSEnergyDistribution::BuildDiscreteLines(
                           k_conversion_834_848_keV_energies_micro_eV,
                           k_conversion_834_848_keV_line_yields));

  return {"Mn-54", k_half_life_seconds, std::move(emissions)};
}

