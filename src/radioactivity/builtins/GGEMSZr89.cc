[[nodiscard]] auto BuildZr89Radionuclide() -> GGEMSRadionuclideDefinition {
  std::vector<GGEMSRadionuclideEmission> emissions;
  emissions.reserve(3U);

  emissions.emplace_back(
    particles::GGEMSParticleType::Positron, k_beta_plus_901_8_keV_yield,
    detail::BuildTabulatedSpectrum(
      {
        .lower_edge_micro_eV = k_beta_plus_901_8_keV_lower_edge_micro_eV,
        .bin_width_micro_eV = k_beta_plus_901_8_keV_bin_width_micro_eV,
      },
      k_beta_plus_901_8_keV_weights));

  emissions.emplace_back(
    particles::GGEMSParticleType::Gamma, k_nuclear_gamma_yield,
    sources::GGEMSEnergyDistribution::BuildDiscreteLines(
      k_nuclear_gamma_energies_micro_eV, k_nuclear_gamma_line_yields));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_conversion_1744_72_keV_yield,
                         sources::GGEMSEnergyDistribution::BuildDiscreteLines(
                           k_conversion_1744_72_keV_energies_micro_eV,
                           k_conversion_1744_72_keV_line_yields));

  return {"Zr-89", k_half_life_seconds, std::move(emissions)};
}

