[[nodiscard]] auto BuildAm241Radionuclide() -> GGEMSRadionuclideDefinition {
  std::vector<GGEMSRadionuclideEmission> emissions;
  emissions.reserve(k_emission_count);

  emissions.emplace_back(
      particles::GGEMSParticleType::Alpha, k_alpha_yield,
      sources::GGEMSEnergyDistribution::BuildDiscreteLines(
          k_alpha_energies_milli_eV, k_alpha_line_yields, "meV"));

  emissions.emplace_back(
      particles::GGEMSParticleType::Gamma, k_gamma_yield,
      sources::GGEMSEnergyDistribution::BuildDiscreteLines(
          k_gamma_energies_milli_eV, k_gamma_line_yields, "meV"));

  emissions.emplace_back(
      particles::GGEMSParticleType::Gamma, k_x_ray_yield,
      sources::GGEMSEnergyDistribution::BuildDiscreteLines(
          k_x_ray_energies_milli_eV, k_x_ray_line_yields, "meV"));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_auger_electron_yield,
                         sources::GGEMSEnergyDistribution::BuildDiscreteLines(
                             k_auger_electron_energies_milli_eV,
                             k_auger_electron_line_yields, "meV"));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_conversion_electron_main_yield,
                         sources::GGEMSEnergyDistribution::BuildDiscreteLines(
                             k_conversion_electron_main_energies_milli_eV,
                             k_conversion_electron_main_line_yields, "meV"));

  emissions.emplace_back(particles::GGEMSParticleType::Electron,
                         k_conversion_electron_weak_yield,
                         sources::GGEMSEnergyDistribution::BuildDiscreteLines(
                             k_conversion_electron_weak_energies_milli_eV,
                             k_conversion_electron_weak_line_yields, "meV"));

  return {"Am-241", k_half_life_seconds, std::move(emissions)};
}

